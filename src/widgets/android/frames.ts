/**
 * Кадры отметки в виджете Android. Анимации у виджета нет (его рисует система из готового
 * дерева), поэтому «анимация» — два кадра: строка «защёлкнулась», пауза, строка ушла.
 */

/** Сколько держится «защёлкнутая» строка, мс: достаточно, чтобы заметить, мало, чтобы раздражать. */
export const DONE_HOLD_MS = 700;

export const pause = (ms: number): Promise<void> => new Promise((resolve) => setTimeout(resolve, ms));
